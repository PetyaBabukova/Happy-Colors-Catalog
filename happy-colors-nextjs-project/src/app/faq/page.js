function internalLink(href, label) {
  return { type: 'link', href, label };
}

function plainTextFromAnswer(answer) {
  if (typeof answer === 'string') {
    return answer;
  }

  return answer
    .map((part) => (typeof part === 'string' ? part : part.label))
    .join('');
}

